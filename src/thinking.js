/** 候选语料池 */
const CORPUS = [
  { name: '三字经', text: SAN_ZI_JING },
  { name: '千字文', text: QIAN_ZI_WEN },
];

/**
 * 生成一段"思考"文本：随机选一篇，随机截取一段连续片段。
 * @param {number} [length] 期望字符数（默认 60~160 随机）
 * @returns {string}
 */
function randomThinking(length) {
  const { text } = CORPUS[Math.floor(Math.random() * CORPUS.length)];
  const chars = Array.from(text);
  const n = length || 60 + Math.floor(Math.random() * 101);
  const max = Math.min(n, chars.length);
  const start = Math.floor(Math.random() * (chars.length - max + 1));
  return chars.slice(start, start + max).join('');
}

